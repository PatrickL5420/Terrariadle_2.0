/**
 * A tiny Terraria 1.4.5 world: a slice of a forest with one player who wanders about, digs with a
 * Copper Pickaxe, chops trees with a Copper Axe and builds with what it digs up.
 *
 * Using the pickaxe and the blocks is the game's own Player.ItemCheck, ported and checked
 * against the game frame by frame (./item-check): the swing, the pickaxe's damage per block
 * (HitTile's cracks and the "miner's wobble"), WorldGen.KillTile (the dig or tink sound, tile
 * dust, grass knocked back to dirt, the block's item dropped; a tree falling, dropping wood and
 * acorns: the game's own code, converted, ./gen) and WorldGen.PlaceTile. Dropped items fall and are pulled in and picked up like any item. Only the player's choices are made
 * up: a little script stands in for the person at the keyboard and mouse.
 */
import {
	fallItem,
	grabReach,
	hitbox,
	intersects,
	pullCommon,
	random,
	type Moving,
	type Rand
} from '$lib/game/items';
import { tileCollision } from './collision';
import { AIR, DIRT, GRASS, isSolid, STONE, TREE, TREES } from './framing';
import { generate, play, UnifiedRandom } from './gen';
import {
	canPlaceAt,
	inRange,
	overlapsPlayer,
	stats,
	type DropCall,
	type Item,
	type ItemWorld,
	type SoundCall
} from './item-check';
import { LightMap, type RGB } from './light';
import { Player } from './player';
import { MARGIN, Tiles } from './tiles';

export type Sound = 'dig' | 'tink' | 'swing' | 'grab';

const PICKAXE = 3509;
const AXE = 3506;
/** Wood and acorns, from trees. */
export const WOOD = 9;
export const ACORN = 27;
/** The blocks the player builds with: dirt, stone and clay blocks (items 2, 3, 133). */
const BLOCKS = [2, 3, 133];

/** The world shown: 150 blocks wide, this many rows deep (the camera follows the player). */
const COLS = 150;
const ROWS = 90;
/** How much sky is kept above the highest ground. */
const SKY_ROWS = 24;
/** The world generated: wider (the passes keep away from a world's edges), a small world's height. */
const GEN_WIDTH = 250;
const GEN_HEIGHT = 1200;

export interface Drop extends Moving {
	item: number;
	stack: number;
	grabbed: boolean;
}

/** Dust (Dust.NewDust / UpdateDust) for dust types 0-2, which just fly off and shrink away. */
export interface Dust {
	type: number;
	x: number;
	y: number;
	vx: number;
	vy: number;
	scale: number;
	rotation: number;
	/** Which of the dust's 3 frames (frame.Y / 10). */
	frame: number;
}

type Goal =
	| { kind: 'idle'; frames: number }
	| { kind: 'walk'; x: number }
	| { kind: 'mine' | 'chop' | 'place'; i: number; j: number };

export class World implements ItemWorld {
	tiles: Tiles;
	light: LightMap;
	/** The game's random numbers (Main.rand), for the game's own code. */
	readonly rand: UnifiedRandom;
	/**
	 * The forest's tree style (TreeTops.GetTreeStyle: one of 6 per world, here a slice of one
	 * forest), as the texture it draws with: Tree_Tops_0, 6 to 9, or 10.
	 */
	readonly treeStyle: number;
	readonly player: Player;
	drops: Drop[] = [];
	dust: Dust[] = [];
	/** The player's inventory: the pickaxe and axe, and the blocks and wood it's picked up. */
	inventory: Item[] = [
		{ type: PICKAXE, stack: 1 },
		{ type: AXE, stack: 1 },
		...[...BLOCKS, WOOD, ACORN].map((type) => ({ type, stack: 0 }))
	];
	/** The ground's height when the world was made, per column: the player keeps it roughly so. */
	surface: number[];

	#goal: Goal = { kind: 'idle', frames: 60 };
	#stuck = 0;
	#sound: (s: Sound, at: { x: number; y: number }) => void = () => {};

	/** The whole world, in tiles: what's shown plus MARGIN (see ./tiles). */
	readonly width = COLS + MARGIN * 2;
	readonly height = ROWS + MARGIN;

	/** A new world, generated by the game's own passes from a random seed (./gen). */
	constructor(private rnd: Rand = random) {
		this.tiles = new Tiles(this.width, this.height, (n) => rnd(n));
		this.light = new LightMap(this.width, this.height);
		this.surface = this.#generate(rnd(0x7fffffff));
		this.rand = new UnifiedRandom(rnd(0x7fffffff));
		const style = rnd(6);
		this.treeStyle = style === 0 ? 0 : style === 5 ? 10 : 5 + style;
		play(this.tiles, this.rand, this);
		const i = MARGIN + Math.trunc(COLS / 2);
		this.player = new Player(i * 16 + 8 - 10, this.surface[i] * 16 - 42);
		this.player.releaseJump = true;
	}

	/** What the player's up to (for tests). */
	get goal(): Readonly<Goal> {
		return this.#goal;
	}

	/** How many columns and rows are shown (the rest is MARGIN). */
	get cols() {
		return this.width - MARGIN * 2;
	}

	get rows() {
		return this.height - MARGIN;
	}

	/**
	 * The game's surface generation (./gen) on a world wider and taller than this one, cut down
	 * to its middle columns and the rows from a little above the highest ground. Water is left
	 * out (it doesn't flow here): its caves are open.
	 */
	#generate(seed: number): number[] {
		const { width: W, height: H, tiles } = this;
		const g = generate(seed, GEN_WIDTH, GEN_HEIGHT);
		const x0 = Math.trunc((GEN_WIDTH - W) / 2);
		let top = GEN_HEIGHT;
		for (let i = x0 + MARGIN; i < x0 + W - MARGIN; i++)
			for (let j = 0; j < top; j++) if (g.tiles.get(i, j).active_()) top = j;
		const y0 = top - SKY_ROWS;
		for (let i = 0; i < W; i++)
			for (let j = 0; j < H; j++) {
				const t = g.tiles.get(x0 + i, y0 + j);
				const k = j * W + i;
				tiles.active[k] = t.active_() ? 1 : 0;
				tiles.type[k] = t.type;
				tiles.wall[k] = t.wall;
				// Trees keep the frames they grew with (the rest are framed below).
				tiles.frameX[k] = t.frameX;
				tiles.frameY[k] = t.frameY;
				// Each block's random variant (frameNumber), as the game's framing on loading picks.
				tiles.frameNumber[k] = this.rnd(3);
			}
		tiles.frameAll();
		return Array.from({ length: W }, (_, i) => this.top(i));
	}

	/** One game frame. `sky` is the sky's colour (Main.ColorOfTheSkies); `sound` plays a sound. */
	update(sky: RGB, sound: (s: Sound, at: { x: number; y: number }) => void) {
		this.#sound = sound;
		this.#think();
		this.player.update(this.tiles, this);
		this.#grow();
		this.#updateDrops();
		this.#updateDust();
		// HitTile.DrawFreshAnimations' clock, for the miner's wobble.
		for (const h of this.player.hitTile.data) h.animationTimeElapsed++;
		this.light.update(this.tiles, sky);
	}

	// ---- What the player's item does to the world (ItemWorld, for ./item-check) ---------------

	/** SquareTileFrame's reset: a new random variant. */
	variant() {
		return this.rnd(3);
	}

	/** The game's sounds by type: 0 dig (chop, on a tree), 21 tink; an item's use sound (Item1) is the swing. */
	sound(s: SoundCall) {
		const name: Sound | null =
			s.type === 0 ? 'dig' : s.type === 21 ? 'tink' : s.type === 2 ? 'swing' : null;
		if (name) this.#sound(name, { x: s.x, y: s.y });
	}

	/** Item.NewItem: the item centred on the rectangle, flung a little. */
	drop(d: DropCall) {
		const r = this.rnd;
		this.drops.push({
			item: d.type,
			stack: d.stack,
			x: d.x + d.w / 2 - 6,
			y: d.y + d.h / 2 - 6,
			w: 12,
			h: 12,
			vx: r(-30, 31) * 0.1,
			vy: r(-30, 31) * 0.1,
			grabbed: false
		});
	}

	/** KillTile_MakeTileDust: dirt 0, stone 1, grass 0 or 2, clay 0, a tree's wood 7. */
	tileDust(i: number, j: number, type: number) {
		const r = this.rnd;
		const dust =
			type === STONE ? 1 : type === GRASS ? (r(2) !== 0 ? 2 : 0) : TREES.includes(type) ? 7 : 0;
		this.#newDust(i * 16, j * 16, 16, 16, dust);
	}

	/** Whether a block could go at (i, j) now: open, shown, built onto, nobody in the way. */
	canPlace(i: number, j: number) {
		const t = this.tiles;
		return (
			t.inView(i, j) &&
			t.at(i, j) === AIR &&
			canPlaceAt(this, i, j) &&
			!overlapsPlayer(this.player, i, j)
		);
	}

	// ---- The world -------------------------------------------------------------------------------

	/**
	 * WorldGen.UpdateWorld's grass, roughly: a random block each frame; grass creeps onto open
	 * dirt beside it (WorldGen.SpreadGrass: the dirt becomes grass, reframed with a new variant).
	 */
	#grow() {
		const t = this.tiles;
		const i = this.rnd(this.width);
		const j = this.rnd(this.height);
		if (t.at(i, j) !== GRASS) return;
		const x = i + this.rnd(-1, 2);
		const y = j + this.rnd(-1, 2);
		if (t.at(x, y) !== DIRT) return;
		const open = [
			[x - 1, y],
			[x + 1, y],
			[x, y - 1],
			[x, y + 1]
		].some(([a, b]) => b >= 0 && t.at(a, b) === AIR);
		if (open) t.convert(x, y, GRASS, this.rnd(3));
	}

	/** Player.GrabItems and WorldItem.UpdateItem for the dropped blocks. */
	#updateDrops() {
		const p = this.player;
		const body = hitbox(p);
		const reach = grabReach(body);
		for (const d of this.drops) {
			if (intersects(body, hitbox(d))) {
				// Player.PickupItem: onto its stack (or into an empty slot), with the grab sound.
				const slot =
					this.inventory.find((it) => it.type === d.item) ??
					this.inventory.find((it) => it.type === 0);
				if (slot) {
					slot.type = d.item;
					slot.stack += d.stack;
				}
				d.item = 0;
				this.#sound('grab', p.center);
				continue;
			}
			if (intersects(reach, hitbox(d))) {
				d.grabbed = true;
				pullCommon(d, body, p.vx, 0.75);
			}
		}
		this.drops = this.drops.filter((d) => d.item);
		for (const d of this.drops) {
			if (d.grabbed) {
				d.grabbed = false;
				d.x += d.vx;
				d.y += d.vy;
				continue;
			}
			fallItem(d, (c) => tileCollision(this.tiles, c));
		}
	}

	/** Dust.NewDust. */
	#newDust(x: number, y: number, w: number, h: number, type: number) {
		const r = this.rnd;
		this.dust.push({
			type,
			x: x + r(Math.max(5, w) - 4) + 4,
			y: y + r(Math.max(5, h) - 4) + 4,
			vx: r(-20, 21) * 0.1,
			vy: r(-20, 21) * 0.1,
			scale: 1 + r(-20, 21) * 0.01,
			rotation: 0,
			frame: r(3)
		});
	}

	/** Dust.UpdateDust for plain dust: flies, falls, spins with its speed and shrinks away. */
	#updateDust() {
		for (const d of this.dust) {
			d.x += d.vx;
			d.y += d.vy;
			d.vy += 0.1;
			d.vx *= 0.99;
			d.rotation += d.vx * 0.5;
			d.scale -= 0.01;
		}
		this.dust = this.dust.filter((d) => d.scale >= 0.1);
	}

	// ---- The made-up part: what the player decides to do ------------------------------------------

	#think() {
		const p = this.player;
		const g = this.#goal;
		p.controls = { left: false, right: false, jump: false, use: false };

		if (g.kind === 'idle') {
			if (--g.frames <= 0) this.#goal = this.#choose();
			return;
		}

		if (g.kind === 'walk') {
			if (this.#walkTo(g.x)) this.#goal = { kind: 'idle', frames: 20 + this.rnd(90) };
			return;
		}

		// Mining, chopping or placing: get within reach (on the ground), then hold the button on it.
		const done =
			g.kind === 'mine'
				? !isSolid(this.tiles.at(g.i, g.j))
				: g.kind === 'chop'
					? !TREES.includes(this.tiles.at(g.i, g.j))
					: this.tiles.at(g.i, g.j) !== AIR;
		if (done) {
			if (p.itemAnimation === 0) this.#goal = { kind: 'idle', frames: 15 + this.rnd(60) };
			return;
		}
		const slot =
			g.kind === 'mine'
				? this.inventory[0]
				: g.kind === 'chop'
					? this.inventory[1]
					: this.#blockToPlace();
		if (g.kind === 'place' && (!this.canPlace(g.i, g.j) || !slot)) {
			if (p.itemAnimation === 0) this.#goal = { kind: 'idle', frames: 30 };
			return;
		}
		// Switching items: only between swings.
		if (p.itemAnimation === 0 && slot) p.item = slot;
		const boost = stats(p.item.type).tileBoost;
		if (!inRange(p, g.i, g.j, boost) || (!p.grounded && p.itemAnimation === 0)) {
			const side = g.i * 16 + 8 < p.center.x ? 1 : -1;
			if (this.#walkTo(g.i * 16 + 8 + side * 40)) {
				// Can't get closer: give up on it.
				if (!inRange(p, g.i, g.j, boost)) this.#goal = { kind: 'idle', frames: 30 };
			}
			return;
		}
		// The cursor on it and the button held; a tap toward it first, to face it.
		const toward = g.i * 16 + 8 < p.center.x ? -1 : 1;
		if (p.itemAnimation === 0 && p.direction !== toward) {
			p.controls.left = toward < 0;
			p.controls.right = toward > 0;
		}
		p.tileTargetX = g.i;
		p.tileTargetY = g.j;
		p.controls.use = true;
	}

	/** Walks toward x, jumping over what's in the way. True once there (or stuck for good). */
	#walkTo(x: number): boolean {
		const p = this.player;
		const dx = x - p.center.x;
		if (Math.abs(dx) < 6) return p.grounded;
		p.controls.left = dx < 0;
		p.controls.right = dx > 0;
		// Blocked by a wall: jump (and keep holding it to jump higher).
		const blocked = p.vx === 0 && p.grounded;
		if (blocked || (this.#stuck > 0 && !p.grounded)) {
			this.#stuck++;
			p.controls.jump = this.#stuck % 40 < 20;
		} else this.#stuck = 0;
		if (this.#stuck > 150) {
			// Too high to jump: dig through it instead.
			this.#stuck = 0;
			const dir = dx < 0 ? -1 : 1;
			const i = Math.trunc((p.center.x + dir * 16) / 16);
			const j = Math.trunc((p.y + p.h - 8) / 16);
			for (const jj of [j - 1, j, j - 2])
				if (isSolid(this.tiles.at(i, jj)) && !TREES.includes(this.tiles.at(i, jj - 1))) {
					this.#goal = { kind: 'mine', i, j: jj };
					return false;
				}
			return true;
		}
		return false;
	}

	/** Whether the tree tile at (i, j) is its trunk (not a root beside it). */
	#isTrunk(i: number, j: number) {
		return this.tiles.at(i, j - 1) === TREE;
	}

	/** A stack of blocks to build with (dirt first). */
	#blockToPlace(): Item | null {
		return this.inventory.find((it) => BLOCKS.includes(it.type) && it.stack > 0) ?? null;
	}

	/** How many blocks the player has. */
	get blocks() {
		return this.inventory.reduce((n, it) => n + (BLOCKS.includes(it.type) ? it.stack : 0), 0);
	}

	/** The top block in column i (the height if there's none). */
	top(i: number) {
		for (let j = 0; j < this.height; j++) if (isSolid(this.tiles.at(i, j))) return j;
		return this.height;
	}

	/** Picks something to do: wander, dig the ground down where it's high, fill it in where low. */
	#choose(): Goal {
		const r = this.rnd;
		const W = this.width;
		const tops = Array.from({ length: W }, (_, i) => this.top(i));
		// Columns in view, not right at its sides.
		const first = MARGIN + 1;
		const last = W - MARGIN - 2;
		const p = this.player;
		// A dropped block nearby: go and get it.
		const loose = this.drops.find((d) => Math.abs(d.x - p.x) < 16 * 8);
		if (loose && r(2) === 0) return { kind: 'walk', x: loose.x + 6 };
		// A tree: chop it down at its foot (the trunk's lowest tile), now and then.
		if (r(6) === 0) {
			const trees: [number, number][] = [];
			for (let i = first; i <= last; i++) {
				const j = tops[i] - 1;
				if (j > 0 && this.tiles.at(i, j) === TREE && this.#isTrunk(i, j)) trees.push([i, j]);
			}
			const near = trees.filter(([i]) => Math.abs(i * 16 - p.x) < 16 * 30);
			const pick = near[r(near.length)] ?? trees[r(trees.length)];
			if (pick) return { kind: 'chop', i: pick[0], j: pick[1] };
		}
		const roll = r(10);
		const blocks = this.blocks;
		if (roll < 4 || (roll < 7 && blocks === 0)) {
			// Mine an open block that's no deeper than 3 below where the ground was.
			const options: [number, number][] = [];
			for (let i = first; i <= last; i++) {
				const j = tops[i];
				// (Not under a tree: it can't go until the tree's gone, WorldGen.CanKillTile.)
				if (
					j < this.rows - 1 &&
					j <= this.surface[i] + 2 &&
					!TREES.includes(this.tiles.at(i, j - 1))
				)
					options.push([i, j]);
			}
			const weighted = options.filter(([i, j]) => j <= this.surface[i] || r(3) === 0);
			const pick = weighted[r(weighted.length)] ?? options[r(options.length)];
			if (pick) return { kind: 'mine', i: pick[0], j: pick[1] };
		}
		if (roll < 7 && blocks > 0) {
			// Build up a column that's no more than 3 above where the ground was.
			const options: [number, number][] = [];
			for (let i = first; i <= last; i++) {
				const j = tops[i] - 1;
				if (j >= 2 && j >= this.surface[i] - 3 && this.canPlace(i, j)) {
					// Lower spots first.
					const weight = j < this.surface[i] ? 1 : 3;
					for (let k = 0; k < weight; k++) options.push([i, j]);
				}
			}
			const pick = options[r(options.length)];
			if (pick) return { kind: 'place', i: pick[0], j: pick[1] };
		}
		return { kind: 'walk', x: first * 16 + r((last - first + 1) * 16) };
	}
}
