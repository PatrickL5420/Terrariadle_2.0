import { Player } from './player';
import { MARGIN, Tiles } from './tiles';

export type Sound = 'dig' | 'tink' | 'swing' | 'grab';

const PICKAXE = 3509;
const AXE = 3506;
/** Wood and acorns, from trees. */
export const WOOD = 9;
export const ACORN = 27;
export const TORCH_ITEM = 8;
/** The item each building piece is put in with. */
const ITEM_FOR: Record<Exclude<Need, 'block'>, number> = {
	wood: 9,
	torch: 8,
	wall: 93,
	bench: 36,
	door: 25,
	table: 32,
	chair: 34
};
/** The blocks the player builds with: dirt, stone and clay blocks (items 2, 3, 133). */
const BLOCKS = [2, 3, 133];

/** The world shown: 150 blocks wide, this many rows deep (the camera follows the player). */
const COLS = 150;
const ROWS = 90;
/** How much sky is kept above the highest ground. */
const SKY_ROWS = 24;
/** The world generated: wider (the passes keep away from a world's edges), a small world's height. */
const GEN_WIDTH = 250;
const GEN_HEIGHT = 1200;

export interface Drop extends Moving {
	item: number;
	stack: number;
	grabbed: boolean;
}

/** Dust (Dust.NewDust / UpdateDust) for dust types 0-2, which just fly off and shrink away. */
export interface Dust {
	type: number;
	x: number;
	y: number;
	vx: number;
	vy: number;
	scale: number;
	rotation: number;
	/** Which of the dust's 3 frames (frame.Y / 10). */
	frame: number;
}

export class World implements ItemWorld {
	tiles: Tiles;
	light: LightMap;
	/** The game's random numbers (Main.rand), for the game's own code. */
	readonly rand: UnifiedRandom;
	/**
	 * The forest's tree style (TreeTops.GetTreeStyle: one of 6 per world, here a slice of one
	 * forest), as the texture it draws with: Tree_Tops_0, 6 to 9, or 10.
	 */
	readonly treeStyle: number;
	readonly player: Player;
	drops: Drop[] = [];
	dust: Dust[] = [];
	/** The player's inventory: the pickaxe and axe, and the blocks and wood it's picked up. */
	inventory: Item[] = [
		{ type: PICKAXE, stack: 1 },
		{ type: AXE, stack: 1 },
		...[...BLOCKS, WOOD, ACORN, TORCH_ITEM].map((type) => ({ type, stack: 0 }))
	];
	/** The ground's height when the world was made, per column: the player keeps it roughly so. */
	surface: number[];

	#task: Task = { kind: 'idle', frames: 60 };
	/** Drops it couldn't get to. */
	#unreachable = new WeakSet<Drop>();
	readonly #doors = new DoorOpeningHelper();
	#follow: Follower | null = null;
	#failures = 0;
	/** Blocks the plans dug out and put in (as tile indexes), to tidy up. */
	#dug = new Set<number>();
	#built = new Set<number>();
	#sound: (s: Sound, at: { x: number; y: number }) => void = () => {};

	/** The whole world, in tiles: what's shown plus MARGIN (see ./tiles). */
	readonly width = COLS + MARGIN * 2;
	readonly height = ROWS + MARGIN;

	/** A new world, generated by the game's own passes from a random seed (./gen). */
	constructor(private rnd: Rand = random) {
		this.tiles = new Tiles(this.width, this.height, (n) => rnd(n));
		this.light = new LightMap(this.width, this.height);
		this.surface = this.#generate(rnd(0x7fffffff));
		this.rand = new UnifiedRandom(rnd(0x7fffffff));
		const style = rnd(6);
		this.treeStyle = style === 0 ? 0 : style === 5 ? 10 : 5 + style;
		play(this.tiles, this.rand, this);
		this.tiles.kept = (i, j) => this.#kept.has(j * this.width + i);
		this.tiles.keepClear = (i, j) => this.#keepClear.has(j * this.width + i);
		// In the middle, or the nearest column with ground (not a cave shaft down to the bottom).
		let i = MARGIN + Math.trunc(COLS / 2);
		for (let d = 0; d < COLS / 2; d++) {
			const near = [i + d, i - d].find(
				(c) => this.surface[c] < this.rows - 4 && this.surface[c + 1] < this.rows - 4
			);
			if (near !== undefined) {
				i = near;
				break;
			}
		}
		this.player = new Player(i * 16 + 8 - 10, this.surface[i] * 16 - 42);
		this.player.releaseJump = true;
	}

	/** What the player's up to (for tests). */
	get task(): Readonly<Task> {
		return this.#task;
	}

	/** How many columns and rows are shown (the rest is MARGIN). */
	get cols() {
		return this.width - MARGIN * 2;
	}

	get rows() {
		return this.height - MARGIN;
	}

	/**
	 * The game's surface generation (./gen) on a world wider and taller than this one, cut down
	 * to its middle columns and the rows from a little above the highest ground. Water is left
	 * out (it doesn't flow here): its caves are open.
	 */
	#generate(seed: number): number[] {
		const { width: W, height: H, tiles } = this;
		const g = generate(seed, GEN_WIDTH, GEN_HEIGHT);
		const x0 = Math.trunc((GEN_WIDTH - W) / 2);
		let top = GEN_HEIGHT;
		for (let i = x0 + MARGIN; i < x0 + W - MARGIN; i++)
			for (let j = 0; j < top; j++) if (g.tiles.get(i, j).active_()) top = j;
		const y0 = top - SKY_ROWS;
		for (let i = 0; i < W; i++)
			for (let j = 0; j < H; j++) {
				const t = g.tiles.get(x0 + i, y0 + j);
				const k = j * W + i;
				tiles.active[k] = t.active_() ? 1 : 0;
				tiles.type[k] = t.type;
				tiles.wall[k] = t.wall;
				// Trees keep the frames they grew with (the rest are framed below).
				tiles.frameX[k] = t.frameX;
				tiles.frameY[k] = t.frameY;
				// Each block's random variant (frameNumber), as the game's framing on loading picks.
				tiles.frameNumber[k] = this.rnd(3);
			}
		tiles.frameAll();
		return Array.from({ length: W }, (_, i) => this.top(i));
	}

	/** One game frame. `sky` is the sky's colour (Main.ColorOfTheSkies); `sound` plays a sound. */
	update(sky: RGB, sound: (s: Sound, at: { x: number; y: number }) => void) {
		this.#sound = sound;
		this.#think();
		// Player.Update: doors walked into open, and close behind (DoorOpeningHelper).
		this.#doors.Update(Main.player[0]);
		this.player.update(this.tiles, this);
		this.#grow();
		this.#updateDrops();
		this.#updateDust();
		// HitTile.DrawFreshAnimations' clock, for the miner's wobble.
		for (const h of this.player.hitTile.data) h.animationTimeElapsed++;
		// A torch in hand lights where it's held (ItemCheck's held-item light).
		const p = this.player;
		const held: [number, number][] =
			p.item.type === TORCH_ITEM && p.item.stack > 0
				? [[Math.trunc(p.itemLocation.x / 16), Math.trunc((p.itemLocation.y - 14) / 16)]]
				: [];
		this.light.update(this.tiles, sky, held);
	}

	// ---- What the player's item does to the world (ItemWorld, for ./item-check) ---------------

	/** SquareTileFrame's reset: a new random variant. */
	variant() {
		return this.rnd(3);
	}

	/** The game's sounds by type: 0 dig (chop, on a tree), 21 tink; an item's use sound (Item1) is the swing. */
	sound(s: SoundCall) {
		const name: Sound | null =
			s.type === 0 ? 'dig' : s.type === 21 ? 'tink' : s.type === 2 ? 'swing' : null;
		if (name) this.#sound(name, { x: s.x, y: s.y });
	}

	/** Item.NewItem: the item centred on the rectangle, flung a little. */
	drop(d: DropCall) {
		const r = this.rnd;
		this.drops.push({
			item: d.type,
			stack: d.stack,
			x: d.x + d.w / 2 - 6,
			y: d.y + d.h / 2 - 6,
			w: 12,
			h: 12,
			vx: r(-30, 31) * 0.1,
			vy: r(-30, 31) * 0.1,
			grabbed: false
		});
	}

	/** KillTile_MakeTileDust: dirt 0, stone 1, grass 0 or 2, clay 0, a tree's wood 7. */
	tileDust(i: number, j: number, type: number) {
		const r = this.rnd;
		const dust =
			type === STONE ? 1 : type === GRASS ? (r(2) !== 0 ? 2 : 0) : TREES.includes(type) ? 7 : 0;
		this.#newDust(i * 16, j * 16, 16, 16, dust);
	}

	/** A wall's new random variant (Framing.WallFrame's reset). */
	wallVariant(i: number, j: number, v: number) {
		this.tiles.wallVariant[j * this.width + i] = v;
	}

	/** Whether a block could go at (i, j) now: open, shown, built onto, nobody in the way. */
	canPlace(i: number, j: number) {
		const t = this.tiles;
		return (
			t.inView(i, j) &&
			t.at(i, j) === AIR &&
			canPlaceAt(this, i, j) &&
			!overlapsPlayer(this.player, i, j)
		);
	}

	// ---- The world -------------------------------------------------------------------------------

	/**
	 * WorldGen.UpdateWorld's grass, roughly: a random block each frame; grass creeps onto open
	 * dirt beside it (WorldGen.SpreadGrass: the dirt becomes grass, reframed with a new variant).
	 */
	#grow() {
		const t = this.tiles;
		const i = this.rnd(this.width);
		const j = this.rnd(this.height);
		if (t.at(i, j) !== GRASS) return;
		const x = i + this.rnd(-1, 2);
		const y = j + this.rnd(-1, 2);
		if (t.at(x, y) !== DIRT) return;
		const open = [
			[x - 1, y],
			[x + 1, y],
			[x, y - 1],
			[x, y + 1]
		].some(([a, b]) => b >= 0 && t.at(a, b) === AIR);
		if (open) t.convert(x, y, GRASS, this.rnd(3));
	}

	/** Player.GrabItems and WorldItem.UpdateItem for the dropped blocks. */
	#updateDrops() {
		const p = this.player;
		const body = hitbox(p);
		const reach = grabReach(body);
		for (const d of this.drops) {
			if (intersects(body, hitbox(d))) {
				// Player.PickupItem: onto its stack (or into an empty slot), with the grab sound.
				const slot =
					this.inventory.find((it) => it.type === d.item) ??
					this.inventory.find((it) => it.type === 0);
				if (slot) {
					slot.type = d.item;
					slot.stack += d.stack;
				}
				d.item = 0;
				this.#sound('grab', p.center);
				continue;
			}
			if (intersects(reach, hitbox(d))) {
				d.grabbed = true;
				pullCommon(d, body, p.vx, 0.75);
			}
		}
		this.drops = this.drops.filter((d) => d.item);
		for (const d of this.drops) {
			if (d.grabbed) {
				d.grabbed = false;
				d.x += d.vx;
				d.y += d.vy;
				continue;
			}
			fallItem(d, (c) => tileCollision(this.tiles, c));
		}
	}

	/** Dust.NewDust. */
	#newDust(x: number, y: number, w: number, h: number, type: number) {
		const r = this.rnd;
		this.dust.push({
			type,
			x: x + r(Math.max(5, w) - 4) + 4,
			y: y + r(Math.max(5, h) - 4) + 4,
			vx: r(-20, 21) * 0.1,
			vy: r(-20, 21) * 0.1,
			scale: 1 + r(-20, 21) * 0.01,
			rotation: 0,
			frame: r(3)
		});
	}

	/** Dust.UpdateDust for plain dust: flies, falls, spins with its speed and shrinks away. */
	#updateDust() {
		for (const d of this.dust) {
			d.x += d.vx;
			d.y += d.vy;
			d.vy += 0.1;
			d.vx *= 0.99;
			d.rotation += d.vx * 0.5;
			d.scale -= 0.01;
		}
		this.dust = this.dust.filter((d) => d.scale >= 0.1);
	}

	// ---- The made-up part: what the player decides to do ------------------------------------------
	//
	// A task at a time (#choose), each "get somewhere, then do something there": the way there is
	// planned (./ai/nav: walking, jumping, digging through, building up with blocks) and carried
	// out step by step (./ai/follow), planned again whenever a step doesn't go as expected.

	#think() {
		const p = this.player;
		p.controls = { left: false, right: false, jump: false, use: false };
		if (this.#lightTheWay()) return;
		const task = this.#task;
		if (task.kind === 'idle') {
			if (--task.frames <= 0) this.#task = this.#choose();
			return;
		}
		if (this.#follow) {
			const r = this.#follow.tick(this);
			if (r === 'running') return;
			this.#follow = null;
			if (r === 'failed') this.#failed();
			return;
		}
		const here = this.#stand();
		if (!here) return; // still in the air
		if (!task.goal.done(here)) {
			const steps = plan(this.tiles, here, task.goal, { blocks: this.blocks });
			if (!steps) return this.#give(task.kind === 'go' ? 'no way there' : 'no way to it');
			this.#follow = new Follower(steps);
			this.#follow.tick(this);
			return;
		}
		// There: do what's to be done.
		if (task.kind === 'go') return this.#give();
		this.#act(task);
	}

	/** The task's action, once in reach: mine, chop or place at the tile. */
	#act(task: Exclude<Task, { kind: 'idle' | 'go' }>) {
		const p = this.player;
		const [i, j] = task.tile;
		const t = this.tiles.at(i, j);
		// (A piece's in: the blueprint's own test, as a wall goes behind the tile.)
		const done =
			task.kind === 'place'
				? task.need
					? pieceDone(this.#map, { i, j, need: task.need })
					: t !== AIR
				: task.kind === 'chop'
					? !TREES.includes(t)
					: !isSolid(t);
		if (done || ++task.frames > 600) {
			if (p.itemAnimation === 0) this.#give(done ? 'done' : 'took too long');
			return;
		}
		const need = task.kind === 'place' ? (task.need ?? 'block') : null;
		if (!this.hold(task.kind === 'chop' ? 'axe' : (need ?? 'pickaxe'))) {
			if (p.itemAnimation === 0) this.#give('nothing to use');
			return;
		}
		if (need && !this.#placeable(i, j, need)) return this.#give("can't place");
		use(p, i, j);
	}

	/** A plan that didn't work out: plan again, or after a few tries, do something else. */
	#failed() {
		if (++this.#failures > 4) this.#give('kept failing');
	}

	/** How tasks have ended: done, or given up on (and why). */
	readonly outcomes: Record<string, number> = {};

	/** On to something else, after a breather. */
	#give(why = 'done') {
		const k = `${this.#task.kind}: ${why}`;
		// A drop it couldn't get to: left (till it moves).
		const task = this.#task;
		if (why !== 'done' && task.kind === 'go' && task.drop) this.#unreachable.add(task.drop);
		// Building and getting nowhere: after a few, it's given up (#build).
		if (why !== 'done' && this.#project) this.#stuckOn++;
		this.outcomes[k] = (this.outcomes[k] ?? 0) + 1;
		this.#task = { kind: 'idle', frames: 15 + this.rnd(60) };
		this.#follow = null;
		this.#failures = 0;
	}

	/** Where the player stands now (null in the air). */
	#stand(): Stand | null {
		const p = this.player;
		if (!p.grounded) return null;
		const s = standOf(p.x, p.y);
		for (const di of [0, -1, 1]) {
			const t = { i: s.i + di, j: s.j };
			if (
				this.tiles.inView(t.i, t.j - 1) &&
				this.#fits(t.i, t.j) &&
				(this.tiles.solid(t.i, t.j) || this.tiles.solid(t.i + 1, t.j))
			)
				return t;
		}
		return s;
	}

	#fits(i: number, j: number) {
		for (let r = j - 3; r < j; r++)
			if (this.tiles.solid(i, r) || this.tiles.solid(i + 1, r)) return false;
		return true;
	}

	// ---- Torches --------------------------------------------------------------------------------

	/** Where a torch is going (null for none), and how long it's been trying. */
	#torchAt: [number, number] | null = null;
	#torchFrames = 0;
	#clock = 0;

	/**
	 * In the dark (at night, or in a hole) with no torch near: puts one up within reach, on
	 * the way (whatever it's doing pauses). Torches are made from wood as needed (the game's
	 * recipe: a Wood and a Gel make 3; gel's taken as unlimited). True while it's at it.
	 */
	#lightTheWay(): boolean {
		const p = this.player;
		const t = this.tiles;
		this.#clock++;
		if (this.#torchAt) {
			const [i, j] = this.#torchAt;
			if (t.at(i, j) !== AIR || ++this.#torchFrames > 40 || !inRange(p, i, j, 0)) {
				if (p.itemAnimation === 0) this.#torchAt = null;
				return p.itemAnimation > 0;
			}
			if (!this.hold('torch')) return true;
			use(p, i, j);
			return true;
		}
		if (this.#clock % 20 !== 0 || !p.grounded || p.itemAnimation > 0) return false;
		// Not in the middle of something: only between steps or while walking.
		const step = this.#follow?.step;
		if (step && step.kind !== 'walk') return false;
		const pi = Math.trunc(p.center.x / 16);
		const pj = Math.trunc(p.center.y / 16);
		const [r, g, b] = this.light.color(pi, pj).map((v) => v / 255);
		if (Math.max(r, g, b) >= 0.45) return false;
		for (let j = pj - 6; j <= pj + 6; j++)
			for (let i = pi - 8; i <= pi + 8; i++) if (t.at(i, j) === TORCH) return false;
		if (!this.#torches()) return false;
		// The spot: a few tiles ahead, about head height.
		let best: [number, number] | null = null;
		let score = Infinity;
		for (let j = pj - 4; j <= pj + 3; j++)
			for (let i = pi - 5; i <= pi + 5; i++) {
				if (t.at(i, j) !== AIR || !t.inView(i, j) || !inRange(p, i, j, 0)) continue;
				// (Not in what it's building: that's kept clear, or its own torch is planned.)
				const k = j * this.width + i;
				if (this.#keepClear.has(k) || this.#kept.has(k)) continue;
				if (!canPlaceTorch(this, i, j)) continue;
				const sc = Math.abs(i - (pi + 3 * p.direction)) + Math.abs(j - (pj - 1)) * 0.6;
				if (sc < score) {
					score = sc;
					best = [i, j];
				}
			}
		if (!best) return false;
		this.#torchAt = best;
		this.#torchFrames = 0;
		return true;
	}

	/** Torches in hand, making 3 from a wood if it's out. */
	#torches(): boolean {
		const torches = this.inventory.find((it) => it.type === TORCH_ITEM && it.stack > 0);
		if (torches) return true;
		const wood = this.inventory.find((it) => it.type === WOOD && it.stack > 0);
		if (!wood) return false;
		wood.stack--;
		const slot =
			this.inventory.find((it) => it.type === TORCH_ITEM) ??
			this.inventory.find((it) => it.type === 0);
		if (!slot) return false;
		slot.type = TORCH_ITEM;
		slot.stack += 3;
		return true;
	}

	/**
	 * Body.hold (./ai/follow): the pickaxe, axe, a stack of blocks or of what a building piece
	 * needs (wood, torches, walls, furniture) in hand, between swings.
	 */
	hold(kind: 'pickaxe' | 'axe' | Need): boolean {
		const p = this.player;
		const slot =
			kind === 'pickaxe'
				? this.inventory[0]
				: kind === 'axe'
					? this.inventory[1]
					: kind === 'block'
						? this.#blockToPlace()
						: (this.inventory.find((it) => it.type === ITEM_FOR[kind] && it.stack > 0) ?? null);
		if (!slot) return false;
		if (p.item === slot) return true;
		if (p.itemAnimation > 0) return false;
		p.item = slot;
		return true;
	}

	/** Body.dug / built: blocks the plans took out or put in, to tidy up later. */
	dug(i: number, j: number) {
		if (this.#dug.size < 300) this.#dug.add(j * this.width + i);
	}

	built(i: number, j: number) {
		this.#built.add(j * this.width + i);
	}

	/** Whether the tree tile at (i, j) is its trunk (not a root beside it). */
	#isTrunk(i: number, j: number) {
		return this.tiles.at(i, j - 1) === TREE;
	}

	/** A stack of blocks to build with (dirt first). */
	#blockToPlace(): Item | null {
		return this.inventory.find((it) => BLOCKS.includes(it.type) && it.stack > 0) ?? null;
	}

	/** How many blocks the player has. */
	get blocks() {
		return this.inventory.reduce((n, it) => n + (BLOCKS.includes(it.type) ? it.stack : 0), 0);
	}

	/** The top block in column i (the height if there's none). */
	top(i: number) {
		for (let j = 0; j < this.height; j++) if (isSolid(this.tiles.at(i, j))) return j;
		return this.height;
	}

	// ---- Building (./ai/build) ----------------------------------------------------------------------

	/** What it's building now, and what it's built. */
	#project: Blueprint | null = null;
	readonly structures: Blueprint[] = [];
	/** What it's building now (for tests). */
	get project(): Blueprint | null {
		return this.#project;
	}
	/** The next step on it (for tests). */
	get projectNext() {
		return this.#project && next(this.#map, this.#project, Math.trunc(this.player.center.x / 16));
	}
	/** Tiles that are part of what it built (not to be mined), and that must stay clear. */
	#kept = new Set<number>();
	#keepClear = new Set<number>();
	#stuckOn = 0;

	/** What building reads of the world (./ai/build: BuildMap). */
	get #map(): BuildMap {
		const t = this.tiles;
		return {
			width: this.width,
			height: this.height,
			maxTilesX: t.maxTilesX,
			maxTilesY: t.maxTilesY,
			solid: (i, j) => t.solid(i, j),
			at: (i, j) => t.at(i, j),
			inView: (i, j) => t.inView(i, j),
			top: (i) => this.top(i),
			placeable: (i, j, need) => this.#placeable(i, j, need),
			wallAt: (i, j) => t.wall[j * this.width + i]
		};
	}

	/** Whether a piece could go at (i, j) now. */
	#placeable(i: number, j: number, need: Need) {
		const t = this.tiles;
		if (!t.inView(i, j)) return false;
		if (need === 'wall') {
			// PlaceThing_Walls: a block or wall beside it.
			const next = (a: number, b: number) => t.at(a, b) !== AIR || t.wall[b * this.width + a] > 0;
			return (
				t.wall[j * this.width + i] === 0 &&
				(next(i + 1, j) || next(i - 1, j) || next(i, j + 1) || next(i, j - 1))
			);
		}
		if (t.at(i, j) !== AIR) return false;
		if (need === 'torch') return canPlaceTorch(this, i, j);
		const tile = FURNITURE_TILE[need];
		if (tile !== undefined) {
			// TileObject.CanPlace: the object's own rules (what it stands on, room for it).
			const box = { v: new TileObject() };
			return TileObject.CanPlace(i, j, tile, 0, this.player.direction, box, true, null);
		}
		return canPlaceAt(this, i, j) && !overlapsPlayer(this.player, i, j);
	}

	/** How many of a thing it has. */
	#count(need: Need) {
		return need === 'block' ? this.blocks : count(this.inventory, ITEM_FOR[need]);
	}

	/**
	 * Something it needs for a piece, made: at once if it needs no station (or one's in reach),
	 * otherwise a trip to the work bench first. Null when there's nothing to make it from.
	 */
	#make(need: Exclude<Need, 'block'>, want: number): Task | 'made' | null {
		const r = recipe(ITEM_FOR[need]);
		if (!hasFor(this.inventory, r)) return null;
		const t = this.tiles;
		if (!r.station || atStation(this.player, (i, j) => t.at(i, j), r.station)) {
			// Main.CraftItem, as many times as wanted (and it has the wood for).
			while (this.#count(need) < want && craft(this.inventory, r));
			return 'made';
		}
		// The nearest bench.
		const pi = Math.trunc(this.player.center.x / 16);
		let best: [number, number] | null = null;
		for (let i = 0; i < this.width; i++)
			for (let j = 0; j < this.height; j++)
				if (t.at(i, j) === r.station && (!best || Math.abs(i - pi) < Math.abs(best[0] - pi)))
					best = [i, j];
		if (!best) return null;
		return { kind: 'go', goal: this.#reach(best[0], best[1], 0) };
	}

	/**
	 * The next task in building: what the blueprint needs done next, or getting what it needs
	 * first (wood from trees, blocks off the bumps), or nothing (no project, and no new one).
	 */
	#build(r: Rand): Task | null {
		if (!this.#project) {
			// A house first; after that, now and then, a tower or a bridge.
			if (r(this.structures.length ? 12 : 3) !== 0) return null;
			const o = {
				first: MARGIN + 1,
				last: this.width - MARGIN - 3,
				rows: this.rows,
				taken: this.structures.map((b) => b.box)
			};
			const near = Math.trunc(this.player.center.x / 16);
			const houses = this.structures.filter((b) => b.kind === 'house').length;
			const site = !houses
				? houseSite(this.#map, near, o)
				: r(2)
					? towerSite(this.#map, near, o)
					: bridgeSite(this.#map, near, o);
			if (!site) return null;
			this.#project = site;
			this.#stuckOn = 0;
			for (const [i, j] of site.clear) this.#keepClear.add(j * this.width + i);
			for (const pc of site.pieces) this.#kept.add(pc.j * this.width + pc.i);
		}
		const b = this.#project;
		const near = Math.trunc(this.player.center.x / 16);
		const n = next(this.#map, b, near);
		if (n.kind === 'stuck') this.#stuckOn++;
		if (n.kind === 'done' || this.#stuckOn > 8) {
			if (n.kind === 'done') this.structures.push(b);
			else {
				for (const [i, j] of b.clear) this.#keepClear.delete(j * this.width + i);
				// What got built of it comes down again (the cleaning up).
				for (const pc of b.pieces) {
					this.#kept.delete(pc.j * this.width + pc.i);
					if (pc.need !== 'block' && this.tiles.at(pc.i, pc.j) !== AIR) this.built(pc.i, pc.j);
				}
			}
			this.#project = null;
			const k = `${b.kind}: ${n.kind === 'done' ? 'built' : 'abandoned'}`;
			this.outcomes[k] = (this.outcomes[k] ?? 0) + 1;
			return null;
		}
		if (n.kind === 'stuck') return null;
		if (n.kind === 'chop') {
			const [i, j] = n.tile;
			return { kind: 'chop', tile: n.tile, goal: this.#reach(i, j, -1), frames: 0 };
		}
		if (n.kind === 'mine') {
			const [i, j] = n.tile;
			return { kind: 'mine', tile: n.tile, goal: this.#reach(i, j, -1), frames: 0 };
		}
		// Enough of what it needs? Wood from trees (and torches from wood), blocks off bumps.
		const want = needs(this.#map, b);
		// Furniture and walls: made from wood (at the bench) if it has none.
		if (n.need !== 'block' && (FURNITURE_TILE[n.need] !== undefined || n.need === 'wall')) {
			if (this.#count(n.need) === 0) {
				const made = this.#make(n.need, want[n.need]);
				if (made === null) return this.#chopTree() ?? this.#starve();
				if (made !== 'made') return made;
			}
		}
		if (n.need === 'torch' && !this.#torches()) return this.#chopTree() ?? this.#starve();
		if (n.need === 'wood' && this.#count('wood') < Math.min(want.wood, 10)) {
			if (this.#count('wood') === 0) return this.#chopTree() ?? this.#starve();
			if (r(2)) return this.#chopTree();
		}
		if (n.need === 'block' && this.blocks === 0) return null; // the gathering below sees to it
		const [i, j] = n.tile;
		return { kind: 'place', tile: n.tile, need: n.need, goal: this.#reach(i, j, 0), frames: 0 };
	}

	/** Nothing to build with, and no way to get it: give the project up (bit by bit). */
	#starve(): null {
		this.#stuckOn++;
		return null;
	}

	/** Chop the nearest tree down (for wood). */
	#chopTree(): Task | null {
		const first = MARGIN + 1;
		const last = this.width - MARGIN - 3;
		const pi = Math.trunc(this.player.center.x / 16);
		const trees: { i: number; j: number }[] = [];
		for (let i = first; i <= last; i++) {
			const j = this.top(i) - 1;
			if (j > 0 && this.tiles.at(i, j) === TREE && this.#isTrunk(i, j)) trees.push({ i, j });
		}
		trees.sort((a, b) => Math.abs(a.i - pi) - Math.abs(b.i - pi));
		const tr = trees[this.rnd(Math.min(2, trees.length))];
		return tr
			? { kind: 'chop', tile: [tr.i, tr.j], goal: this.#reach(tr.i, tr.j, -1), frames: 0 }
			: null;
	}

	// ---- Goals -------------------------------------------------------------------------------------

	/** Standing on the open surface around column x. */
	#surface(x: number): Goal {
		return { i: x, done: (s) => Math.abs(s.i - x) <= 1 && open(this.tiles, s.i, s.j) };
	}

	/** Standing where tile (x, y) is in reach (Player.IsInTileInteractionRange, tileBoost `tb`), clear of it. */
	#reach(x: number, y: number, tb: number): Goal {
		const rx = 5 + tb;
		const ry = 3 + tb;
		return {
			i: x,
			done: (s) =>
				x >= s.i - rx &&
				x <= s.i + 1 + rx &&
				y >= s.j - 3 - ry &&
				y <= s.j - 1 + ry &&
				// Not where it stands (or would stand on).
				!((x === s.i || x === s.i + 1) && y >= s.j - 3 && y <= s.j)
		};
	}

	/** Picks something to do: weighed by what's needed, then what's near. */
	#choose(): Task {
		const r = this.rnd;
		const W = this.width;
		const t = this.tiles;
		const p = this.player;
		const first = MARGIN + 1;
		const last = W - MARGIN - 3;
		const pi = Math.trunc(p.center.x / 16);
		const near = <T extends { i: number }>(list: T[]) =>
			list.sort((a, b) => Math.abs(a.i - pi) - Math.abs(b.i - pi))[r(Math.min(3, list.length))];

		// Something dropped nearby: pick it up.
		const loose = this.drops.find(
			(d) => Math.abs(d.x - p.x) < 16 * 25 && !this.#unreachable.has(d)
		);
		if (loose) {
			const di = Math.trunc((loose.x + loose.w / 2) / 16);
			const dj = Math.trunc((loose.y + loose.h) / 16);
			return {
				kind: 'go',
				drop: loose,
				goal: { i: di, done: (s) => Math.abs(s.i + 1 - di) <= 1 && Math.abs(s.j - dj) <= 2 }
			};
		}

		// Building: on with what it's building, or now and then something new.
		const work = this.#build(r);
		if (work) return work;

		// Cleaning up: blocks it built to get about (pillars, bridges) come down; holes it dug go
		// back in, bottom first.
		const built = [...this.#built]
			.map((k) => ({ i: k % W, j: Math.trunc(k / W) }))
			.filter(({ i, j }) => {
				const solid = isSolid(t.at(i, j)) && !this.#kept.has(j * W + i);
				if (!solid) this.#built.delete(j * W + i);
				return solid;
			});
		if (built.length && r(2) === 0) {
			const b = near(built);
			this.#built.delete(b.j * W + b.i);
			return { kind: 'mine', tile: [b.i, b.j], goal: this.#reach(b.i, b.j, -1), frames: 0 };
		}
		const holes = [...this.#dug]
			.map((k) => ({ i: k % W, j: Math.trunc(k / W) }))
			.filter(({ i, j }) => {
				const open = t.at(i, j) === AIR && !this.#keepClear.has(j * W + i);
				if (!open) this.#dug.delete(j * W + i);
				return open;
			});
		if (holes.length && this.blocks > 0 && r(2) === 0) {
			// The lowest that a block can go into now (not over the player's head).
			const me = standOf(p.x, p.y);
			const ok = holes
				.filter(({ i, j }) => this.canPlace(i, j) && !(i >= me.i - 1 && i <= me.i + 2 && j < me.j))
				.sort((a, b) => b.j - a.j);
			const h = ok[0];
			if (h) {
				this.#dug.delete(h.j * W + h.i);
				return { kind: 'place', tile: [h.i, h.j], goal: this.#reach(h.i, h.j, 0), frames: 0 };
			}
		}

		// Short of blocks: mine some, off the tops of the bumps nearby (it flattens, not pits).
		if (this.blocks < 10 && r(2) === 0) {
			const peaks: { i: number; j: number }[] = [];
			for (let i = first; i <= last; i++) {
				const j = this.top(i);
				if (j >= this.rows - 1 || TREES.includes(t.at(i, j - 1)) || this.#kept.has(j * W + i))
					continue;
				if (j <= this.top(i - 1) && j <= this.top(i + 1)) peaks.push({ i, j });
			}
			const pk = near(peaks);
			if (pk)
				return { kind: 'mine', tile: [pk.i, pk.j], goal: this.#reach(pk.i, pk.j, -1), frames: 0 };
		}

		// A tree, now and then: chopped at its foot. Straight away in the dark with no torches
		// or wood to make them from.
		const c = p.center;
		const dark =
			Math.max(...this.light.color(Math.trunc(c.x / 16), Math.trunc(c.y / 16))) < 0.45 * 255;
		const noLight = !this.inventory.some(
			(it) => (it.type === TORCH_ITEM || it.type === WOOD) && it.stack > 0
		);
		if (r(6) === 0 || (dark && noLight)) {
			const trees: { i: number; j: number }[] = [];
			for (let i = first; i <= last; i++) {
				const j = this.top(i) - 1;
				if (j > 0 && t.at(i, j) === TREE && this.#isTrunk(i, j)) trees.push({ i, j });
			}
			const tr = near(trees);
			if (tr)
				return { kind: 'chop', tile: [tr.i, tr.j], goal: this.#reach(tr.i, tr.j, -1), frames: 0 };
		}

		// Otherwise, off somewhere on the surface.
		return { kind: 'go', goal: this.#surface(first + r(last - first + 1)) };
	}
}

type Task =
	| { kind: 'idle'; frames: number }
	| { kind: 'go'; goal: Goal; drop?: Drop }
	| {
			kind: 'mine' | 'chop' | 'place';
			tile: [number, number];
			goal: Goal;
			frames: number;
			/** What's placed (blocks by default). */
			need?: Need;
	  };
