#!/usr/bin/env node
/**
 * Generates src/lib/world/frame-tables.ts: the frame tables of WorldGen.TileFrameCosmetic (the
 * grass, dirt-blend and basic blocks), converted from the game's code by ./csharp-to-ts.mjs. The
 * code around them is ported by hand in src/lib/world/framing.ts. Run after build.mjs (it reads
 * the extracted oracle/game/WorldGen.cs): node tools/verify/port/frame-tables.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { convert } from './csharp-to-ts.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '../../../src/lib/world/frame-tables.ts');
const lines = readFileSync(join(here, '../oracle/game/WorldGen.cs'), 'utf8').split('\n');

const find = (from, test, what) => {
	for (let k = from; k < lines.length; k++) if (test(lines[k])) return k;
	throw new Error(`not found: ${what}`);
};
const start = find(
	0,
	(l) => l.includes('public static void TileFrameCosmetic('),
	'TileFrameCosmetic'
);
const CULL =
	'tileMergeCulling.Cull(ref up, ref down, ref left, ref right, ref upLeft, ref upRight, ref downLeft, ref downRight);';

// The grass block: its table runs from after the first Cull to the dirt merge after it.
const grassAt = find(
	start,
	(l) => l.includes('int num11 = TileID.Sets.NeedsGrassFramingDirt[num];'),
	'grass'
);
const grassFrom = find(grassAt, (l) => l.trim() === CULL, 'grass cull') + 1;
const grassTo = find(
	grassFrom,
	(l) => l.includes('if (num11 >= 0 && num11 < TileID.Count && TileID.Sets.Dirt[num11])'),
	'grass end'
);

// The blend block: from after its Cull to the end of the `if` it's in.
const mergeAt = find(
	start,
	(l) => l.includes('if (val.X == -1 && val.Y == -1 && (Main.tileMergeDirt[num]'),
	'merge'
);
const mergeFrom = find(mergeAt, (l) => l.trim() === CULL, 'merge cull') + 1;
const mergeTo = find(mergeFrom, (l) => l === '\t\t\t\t}', 'merge end');

// The basic block: its table starts at the all-four-sides case.
const basicAt = find(start, (l) => l === '\t\t\t\tif (val.X < 0 || val.Y < 0)', 'basic');
const basicFrom = find(
	basicAt,
	(l) => l === '\t\t\t\t\tif (up == num && down == num && left == num && right == num)',
	'basic table'
);
const basicTo = find(basicFrom, (l) => l === '\t\t\t\t}', 'basic end');

const names = {
	num: 'T',
	num11: 'D',
	up: 'n.up',
	down: 'n.down',
	left: 'n.left',
	right: 'n.right',
	upLeft: 'n.upLeft',
	upRight: 'n.upRight',
	downLeft: 'n.downLeft',
	downRight: 'n.downRight',
	mergeUp: 'm.up',
	mergeDown: 'm.down',
	mergeLeft: 'm.left',
	mergeRight: 'm.right'
};
const opts = {
	names,
	selector: 'num6',
	targets: ['val.X', 'val.Y'],
	pick: 'pick',
	statements: [[/^tileMergeCulling\.Cull\(.*\);$/, 'cull(n);']]
};
const body = (from, to) =>
	convert(lines.slice(from, to), opts)
		.map((l) => l.replace(/^\t{4}/, '\t'))
		.join('\n');

const tables = [body(grassFrom, grassTo), body(mergeFrom, mergeTo), body(basicFrom, basicTo)].join(
	'\n'
);
const CULL_TS = `/** TileMergeCullCache.Cull: only blocks with Echo Coating are culled, and there are none. */
const cull = (n: Neighbours) => void n;
`;
const ts = `// Generated by tools/verify/port/frame-tables.mjs from Terraria 1.4.5's WorldGen.TileFrameCosmetic
// (its grass, dirt-blend and basic frame tables). Don't edit: change the generator, or the hand
// port around these in ./framing.ts. Each pick(...) is the three random variants' frames.
/* eslint-disable no-dupe-else-if -- the game's tables have unreachable branches; kept as they are */
import type { Merge, Neighbours, Pick } from './framing';

${tables.includes('cull(') ? CULL_TS : ''}
/** The grass block (NeedsGrassFraming): grass type T over dirt type D. */
export function grassFrames(T: number, D: number, i: number, j: number, n: Neighbours, pick: Pick) {
${body(grassFrom, grassTo)}
}

/** The blend block (tileMergeDirt / ChecksForMerge): -2 marks a neighbour it blends into. */
export function mergeFrames(T: number, n: Neighbours, m: Merge, pick: Pick) {
${body(mergeFrom, mergeTo)}
}

/** The basic block: joins only with its own type T. */
export function basicFrames(T: number, n: Neighbours, pick: Pick) {
${body(basicFrom, basicTo)}
}
`;
writeFileSync(OUT, ts);
console.log(
	`Wrote ${OUT}: grass ${grassTo - grassFrom}, blend ${mergeTo - mergeFrom}, basic ${basicTo - basicFrom} lines of the game's code.`
);
